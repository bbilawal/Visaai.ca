/**
 * Canadian arrival places → the zone of their local time. The interview asks
 * the arrival time in local time where the flight lands, so the zone is the
 * Canadian airport's. Only places wholly inside one zone are listed (no
 * province split across two: British Columbia, Ontario, Quebec, Labrador).
 */
const CANADIAN_PLACE_ZONES: ReadonlyArray<[RegExp, string]> = [
  [/\b(st\.? john'?s|newfoundland|yyt)\b/, 'Newfoundland Time'],
  [
    /\b(halifax|moncton|fredericton|saint john|charlottetown|nova scotia|new brunswick|prince edward island|yhz|yqm|yfc|ysj|yyg)\b/,
    'Atlantic Time',
  ],
  [
    /(\b(toronto|pearson|billy bishop|ottawa|trudeau|hamilton|yyz|ytz|yow|yul|yqb|yhm)\b|montr[eé]al|qu[eé]bec city)/,
    'Eastern Time',
  ],
  [
    /\b(winnipeg|regina|saskatoon|manitoba|saskatchewan|ywg|yqr|yxe)\b/,
    'Central Time',
  ],
  [/\b(calgary|edmonton|alberta|yyc|yeg)\b/, 'Mountain Time'],
  [
    /\b(vancouver|victoria|kelowna|abbotsford|yvr|yyj|ylw|yxx)\b/,
    'Pacific Time',
  ],
];

/** North American zone names and abbreviations → the option text. */
const ZONE_WORDS: ReadonlyArray<[RegExp, string]> = [
  [/^(newfoundland( time)?|n[sd]t)$/, 'Newfoundland Time'],
  [/^(atlantic( time)?|a[sd]t)$/, 'Atlantic Time'],
  [/^(eastern( time)?|e[sd]t|et)$/, 'Eastern Time'],
  [/^(central( time)?|c[sd]t|ct)$/, 'Central Time'],
  [/^(mountain( time)?|m[sd]t|mt)$/, 'Mountain Time'],
  [/^(pacific( time)?|p[sd]t|pt)$/, 'Pacific Time'],
];

/**
 * The time-zone option for an answer: an option named exactly, a North
 * American zone name, or a Canadian city or airport wholly in one zone.
 * Anything else (a place the list cannot place) is undefined: never guessed.
 */
export function etaTimeZoneOption(raw: string | undefined): string | undefined {
  const t = raw?.trim().toLowerCase().replace(/\s+/g, ' ');
  if (!t) return undefined;
  const exact = ETA_TIME_ZONES.find((z) => z.toLowerCase() === t);
  if (exact) return exact;
  const word = ZONE_WORDS.find(([re]) => re.test(t));
  if (word) return word[1];
  return CANADIAN_PLACE_ZONES.find(([re]) => re.test(t))?.[1];
}
