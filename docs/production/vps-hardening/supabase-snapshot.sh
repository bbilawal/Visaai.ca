#!/usr/bin/env bash
# =============================================================================
# EXAMPLE — REVIEW BEFORE USE.
# =============================================================================
# Pre-migration Supabase snapshot + restore helper.
#
# WHY THIS EXISTS
#   Migrations in this repo are FORWARD-ONLY (`supabase db push`, no `down`
#   files). There is no code path that reverses a schema change. So the only
#   real rollback for a bad migration is: (a) restore from a snapshot you took
#   seconds before, or (b) roll forward with a corrective migration. Always take
#   the snapshot FIRST.
#
# TWO SNAPSHOT MECHANISMS — pick per plan:
#   1. Supabase PITR (Point-In-Time Recovery) — Pro plan + add-on. Preferred:
#      continuous, no dump needed. Before a risky migration just note the UTC
#      timestamp; restore via Dashboard → Database → Backups → PITR, or the
#      Management API. This script's pg_dump path is the portable fallback.
#   2. pg_dump logical snapshot (any plan) — what this script does. Good for
#      small/medium DBs. For large DBs prefer PITR (a multi-GB dump is slow and
#      the restore window is long).
#
# CREDENTIALS
#   Set SUPABASE_DB_URL to the *direct* (session) connection string, NOT the
#   transaction pooler (pg_dump needs a session connection). Find it in
#   Dashboard → Project Settings → Database → Connection string (URI, "Session").
#     export SUPABASE_DB_URL='postgresql://postgres:PASS@db.<ref>.supabase.co:5432/postgres'
# =============================================================================

set -Eeuo pipefail

SNAP_DIR="${SNAP_DIR:-/var/backups/visaai}"
STAMP="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="${SNAP_DIR}/visaai-${STAMP}.dump"

: "${SUPABASE_DB_URL:?set SUPABASE_DB_URL to the direct/session connection string}"
mkdir -p "$SNAP_DIR"

usage() { echo "usage: $0 {snapshot | restore <dumpfile>}"; exit 1; }

snapshot() {
  echo "[snap] dumping to $OUT (custom format, compressed)…"
  # --format=custom → restore selectively with pg_restore; --no-owner/--no-acl
  # so a restore into a fresh project doesn't choke on role grants.
  pg_dump "$SUPABASE_DB_URL" \
    --format=custom --no-owner --no-acl \
    --file="$OUT"
  echo "[snap] done: $OUT ($(du -h "$OUT" | cut -f1))"
  # Retention: keep last 14, prune older. Adjust to your RPO.
  # shellcheck disable=SC2012  # dump names are generated by this script: no spaces, no newlines
  ls -1t "${SNAP_DIR}"/visaai-*.dump 2>/dev/null | tail -n +15 | xargs -r rm -f
  echo "[snap] ship this file OFF the box (rclone/s3) — a VPS-local backup dies with the VPS."
}

restore() {
  local dump="${1:?path to .dump required}"
  [[ -f "$dump" ]] || { echo "no such dump: $dump"; exit 1; }
  echo "[restore] !!! This overwrites schema+data in the target DB."
  echo "[restore] Target: $(echo "$SUPABASE_DB_URL" | sed -E 's#://[^@]+@#://***@#')"
  read -r -p "Type RESTORE to proceed: " confirm
  [[ "$confirm" == "RESTORE" ]] || { echo "aborted"; exit 1; }
  # --clean --if-exists drops objects before recreating; single txn so a failure
  # leaves the DB untouched rather than half-restored.
  pg_restore --clean --if-exists --no-owner --no-acl --single-transaction \
    --dbname="$SUPABASE_DB_URL" "$dump"
  echo "[restore] complete."
}

case "${1:-}" in
  snapshot) snapshot ;;
  restore)  restore "${2:-}" ;;
  *)        usage ;;
esac
